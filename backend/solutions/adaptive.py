"""
Оценка качества решения задачи.

Формула оценки прогресса:
    P = S + T + H

где
    S — успешность:       2 — задача решена, 0 — не решена;
    T — оценка времени:   2 — менее 10 мин, 1 — от 10 до 20 мин, 0 — более 20 мин;
    H — использование подсказки:
        1 — подсказки не было ИЛИ использовались только наводящие (уровень 1),
        0 — была использована подсказка уровня 2 (конкретная).

Диапазон значений P: от 0 до 5. Чем выше значение, тем «сильнее» считается
выполнение. Используется моделью мастерства (mastery.py) для решения,
выдавать ли обучающемуся закрепляющую задачу-вариацию.

Принятая интерпретация:
    P = 5            — «сильное» решение (быстро, без конкретной подсказки, верно);
    2 <= P <= 4      — «слабое» решение (требуется закрепление);
    P <= 1           — задача не решена.
"""

# Пороговое значение для «сильного» решения. См. подраздел 2.5 пояснительной записки.
STRONG_SCORE_THRESHOLD = 5

# Временные границы оценки T (секунды)
T_FAST_SEC = 10 * 60    # < 10 мин — T = 2
T_MEDIUM_SEC = 20 * 60  # 10-20 мин — T = 1; > 20 мин — T = 0

# Уровень подсказки, за который снимается балл H. Подсказка 1 (сократический
# вопрос) считается бесплатной — она поощряет рефлексию, а не подменяет решение.
HINT_LEVEL_PENALIZED = 2


def calculate_progress_score(is_solved: bool, time_spent_sec: int, max_hint_level: int) -> int:
    """Вычисляет показатель прогресса P = S + T + H.

    max_hint_level — максимальный уровень подсказки, который студент использовал
    для этой задачи к моменту submission. 0 — подсказок не было.
    """
    s = 2 if is_solved else 0

    if time_spent_sec < T_FAST_SEC:
        t = 2
    elif time_spent_sec <= T_MEDIUM_SEC:
        t = 1
    else:
        t = 0

    h = 0 if max_hint_level >= HINT_LEVEL_PENALIZED else 1

    return s + t + h


def score_for_submission(submission) -> int:
    """Вычисляет P-скор по объекту Submission."""
    is_solved = submission.status == 'accepted'
    return calculate_progress_score(
        is_solved,
        submission.time_spent,
        submission.max_hint_level,
    )
